//! Cached, local previews. Renderers receive only a small JPEG data URI, never
//! arbitrary filesystem access or permission to load remote images.
use crate::state::AppState;
use base64::Engine as _;
use crowdm_engine::JobState;
use std::process::Stdio;
use tauri::State;

#[tauri::command]
pub async fn job_thumbnail(state: State<'_, AppState>, id: uuid::Uuid) -> Result<Option<String>, String> {
    let job = state.engine.job(id).ok_or("Download not found")?.job;
    if job.state != JobState::Completed || !matches!(job.category.as_str(), "videos" | "images" | "audio") {
        return Ok(None);
    }
    static DECODERS: std::sync::OnceLock<tokio::sync::Semaphore> = std::sync::OnceLock::new();
    let _permit = DECODERS.get_or_init(|| tokio::sync::Semaphore::new(2)).acquire().await.map_err(|e| e.to_string())?;
    let dir = state.data_dir.join("previews");
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    // v2 invalidates first-frame previews generated by the previous version.
    let cache = dir.join(format!("v2-{}-{}.jpg", id, job.completed_at.unwrap_or_default()));
    if !cache.is_file() {
        let video = job.category == "videos";
        let duration = if video { duration(&job.target_path()).await } else { None };
        let positions = if video {
            vec![duration.unwrap_or(0.0) * 0.1, duration.unwrap_or(10.0) * 0.5, duration.unwrap_or(20.0) * 0.8]
        } else {
            vec![0.0]
        };
        let temporary = dir.join(format!("preview-{}.jpg", uuid::Uuid::new_v4()));
        for position in positions {
            if render(&job.target_path(), &temporary, video, position).await {
                // Another request for this job may have completed first.
                if !cache.is_file() {
                    let _ = std::fs::rename(&temporary, &cache);
                }
                break;
            }
        }
        let _ = std::fs::remove_file(&temporary);
        if !cache.is_file() {
            return Ok(None);
        }
    }
    let bytes = std::fs::read(&cache).map_err(|e| e.to_string())?;
    if bytes.len() > 64 * 1024 {
        return Ok(None);
    }
    Ok(Some(format!("data:image/jpeg;base64,{}", base64::engine::general_purpose::STANDARD.encode(bytes))))
}

fn hidden(cmd: &mut tokio::process::Command) {
    #[cfg(windows)]
    cmd.creation_flags(0x0800_0000);
    cmd.kill_on_drop(true).stdin(Stdio::null());
}

async fn duration(path: &std::path::Path) -> Option<f64> {
    let mut cmd = tokio::process::Command::new(crowdm_engine::media::tool("ffprobe"));
    hidden(&mut cmd);
    cmd.args(["-v", "error", "-protocol_whitelist", "file,pipe", "-show_entries", "format=duration", "-of", "csv=p=0"])
        .arg(path)
        .stderr(Stdio::null());
    let output = tokio::time::timeout(std::time::Duration::from_secs(5), cmd.output()).await.ok()?.ok()?;
    let value: f64 = String::from_utf8_lossy(&output.stdout).trim().parse().ok()?;
    (value.is_finite() && value > 0.0).then_some(value)
}

async fn render(path: &std::path::Path, output: &std::path::Path, video: bool, seek: f64) -> bool {
    let _ = std::fs::remove_file(output);
    let mut cmd = tokio::process::Command::new(crowdm_engine::media::tool("ffmpeg"));
    hidden(&mut cmd);
    cmd.args([
        "-hide_banner",
        "-loglevel",
        "error",
        "-nostdin",
        "-max_alloc",
        "67108864",
        "-threads",
        "1",
        "-filter_threads",
        "1",
        "-protocol_whitelist",
        "file,pipe",
    ]);
    if video {
        cmd.arg("-ss").arg(format!("{seek:.3}"));
    }
    cmd.arg("-i").arg(path).args(["-map", "0:v:0", "-frames:v", "1", "-t", "3", "-vf"]);
    cmd.arg(if video {
        "blackframe=amount=0:threshold=24,metadata=mode=select:key=lavfi.blackframe.pblack:value=95:function=less,scale=128:128:force_original_aspect_ratio=decrease,thumbnail=12"
    } else { "scale=128:128:force_original_aspect_ratio=decrease" });
    cmd.args(["-q:v", "4", "-update", "1", "-y"]).arg(output).stdout(Stdio::null()).stderr(Stdio::null());
    let success =
        matches!(tokio::time::timeout(std::time::Duration::from_secs(10), cmd.status()).await, Ok(Ok(status)) if status.success());
    success && std::fs::metadata(output).is_ok_and(|m| m.len() > 4 && m.len() <= 64 * 1024)
}
